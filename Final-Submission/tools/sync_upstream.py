"""Pull organizer updates and regenerate the root Controller.py from upstream.

Usage:  python tools/sync_upstream.py            # pull submodules + regenerate
        python tools/sync_upstream.py --no-pull  # regenerate only

Controller.py = upstream STU4-Solution/Controller.py boilerplate (verbatim, up to the
"DON'T CHANGE ANY OF THE ABOVE" banner) + TEAM_SECTION below. Never edit Controller.py by hand.

sims/PLAN_<n>_<name>.simconf = upstream FINAL_SUBMISSION.simconf with only the Controller system's
Inst_Parameters extended by the part names below (read by Systems.BasicController.SpaceTeamsSim.choices).
Physics, debris, radar, jets and scoring stay exactly the organizers'. Never edit them by hand.
TRAINING_RADAR_CAPTURE.simconf is a separate lab scene with its own data collector.
TEST_LIFT_ROTATE.simconf selects the local lift-and-turn controller.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM_CONTROLLER = ROOT / "submodules" / "STU4-Solution" / "Controller.py"
OUTPUT = ROOT / "Controller.py"
END_MARKER = "# DON'T CHANGE ANY OF THE ABOVE."
UPSTREAM_SIM = ROOT / "submodules" / "STU4-Sim" / "Sims" / "FINAL_SUBMISSION.simconf"
SIMS = ROOT / "sims"
# Plan number -> Planners.PLANNERS name. Plan 4 (team_pipeline) is plan 7's search plus the route-zone switches.
SIM_PLANS = {1: "fewest_points", 2: "linear_program", 3: "lattice", 4: "team_pipeline", 5: "conjunction", 6: "barrier",
             7: "velocity_obstacle", 8: "astar", 9: "cost_lattice", 10: "real_calibrated",
             11: "v11", 13: "v13", 14: "v14", 15: "musubi", 16: "v16", 17: "v16_morning"}
SIM_PARTS = {"Camera": "off", "Record": "on"}     # every plan flies without vision and saves flightlogs/*.npz


def sim_variants(n: int, name: str) -> list[str]:
    """Every config variant of a plan (Systems/plans/plan_<n>_<name>/configs/<variant>.json) except default.json,
    which the plain PLAN_<n>_<name>.simconf already flies."""
    return sorted(p.stem for p in (ROOT / "Systems" / "plans" / f"plan_{n}_{name}" / "configs").glob("*.json")
                  if p.stem != "default")

TEAM_SECTION = '''

#####################################################################################
# TEAM BATASHA SECTION (generated by tools/sync_upstream.py; edit Systems/ instead) #
#####################################################################################

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from Systems.BasicController import run

run(sys.modules[__name__])
'''


def build_controller() -> str:
    lines = UPSTREAM_CONTROLLER.read_text(encoding="utf-8").splitlines(keepends=True)
    marker = next(i for i, line in enumerate(lines) if line.startswith(END_MARKER))
    # Keep the marker line and the '#####' banner line under it.
    return "".join(lines[: marker + 2]) + TEAM_SECTION


def build_sims() -> dict[Path, dict]:
    """{path: simconf} for every plan in SIM_PLANS."""
    out = {}
    for n, name in SIM_PLANS.items():
        sim = json.loads(UPSTREAM_SIM.read_text(encoding="utf-8"))
        controller = next(s for s in sim["SystemManager"]["Systems"] if s["Nametag"] == "Controller")
        controller["Inst_Parameters"].update({"Planner": name, **SIM_PARTS})
        out[SIMS / f"PLAN_{n}_{name}.simconf"] = sim
        for variant in sim_variants(n, name):
            sim_v = json.loads(json.dumps(sim))
            params = next(s for s in sim_v["SystemManager"]["Systems"] if s["Nametag"] == "Controller")["Inst_Parameters"]
            preset = ROOT / "Systems" / "plans" / f"plan_{n}_{name}" / "configs" / f"{variant}.json"
            params.update(Variant=variant, Camera=json.loads(preset.read_text()).get("camera", SIM_PARTS["Camera"]))
            out[SIMS / f"PLAN_{n}_{name}_{variant}.simconf"] = sim_v
    return out


def build_radar_training_scene() -> dict:
    """Build the lab scene without enabling capture in any competition plan."""
    sim = json.loads(UPSTREAM_SIM.read_text(encoding="utf-8"))
    systems = sim["SystemManager"]["Systems"]
    entries = {system["Nametag"]: system for system in systems}
    controller = entries["Controller"]
    parameters = controller["Inst_Parameters"]
    camera_refs = {key: parameters[key] for key in ("Shuttle", "Phobos", "Target", "TopCamera", "BottomCamera")}
    parameters.update(Planner="real_calibrated", Camera="off")
    entries["Scoring"]["Active"] = False
    systems.append({
        "Nametag": "Radar_Capture",
        "Type": "Python",
        "Active": True,
        "Source": controller["Source"].rsplit("/", 1)[0] + "/Radar_Capture.py",
        "Inst_Parameters": {
            **camera_refs,
            "NumDebris": entries["Radar"]["Inst_Parameters"]["NumDebris"],
            "CapturePurpose": "offline_training_dataset",
            "CaptureInterval_s": 2.0,
        },
    })
    return sim


def build_lift_rotate_scene() -> dict:
    sim = json.loads(UPSTREAM_SIM.read_text(encoding="utf-8"))
    controller = next(s for s in sim["SystemManager"]["Systems"] if s["Nametag"] == "Controller")
    controller["Inst_Parameters"]["ManeuverTest"] = "lift_rotate"
    return sim


def main() -> None:
    if "--no-pull" not in sys.argv:
        subprocess.run(["git", "submodule", "update", "--init", "--remote", "--merge"], cwd=ROOT, check=True)
    OUTPUT.write_text(build_controller(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    scenes = build_sims()
    scenes[SIMS / "TRAINING_RADAR_CAPTURE.simconf"] = build_radar_training_scene()
    scenes[SIMS / "TEST_LIFT_ROTATE.simconf"] = build_lift_rotate_scene()
    for path, sim in scenes.items():
        path.write_text(json.dumps(sim, indent="\t") + "\n", encoding="utf-8", newline="\n")
        print(f"Wrote {path.relative_to(ROOT)}")
    subprocess.run(["git", "diff", "--stat", "--submodule", "--", "submodules", OUTPUT.name, SIMS.name], cwd=ROOT)


if __name__ == "__main__":
    main()
